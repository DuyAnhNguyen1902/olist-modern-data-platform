INSERT INTO warehouse.dim_date (
    date_key, full_date, day_of_month, day_of_week, day_name, week_of_year,
    month_number, month_name, quarter_number, year_number, is_weekend
)
WITH all_source_dates AS (
    SELECT order_purchase_timestamp::DATE AS source_date FROM staging.stg_orders
    UNION ALL
    SELECT order_approved_at::DATE FROM staging.stg_orders
    UNION ALL
    SELECT order_delivered_carrier_date::DATE FROM staging.stg_orders
    UNION ALL
    SELECT order_delivered_customer_date::DATE FROM staging.stg_orders
    UNION ALL
    SELECT order_estimated_delivery_date::DATE FROM staging.stg_orders
    UNION ALL
    SELECT shipping_limit_date::DATE FROM staging.stg_order_items
),
date_boundaries AS (
    SELECT MIN(source_date) AS min_date, MAX(source_date) AS max_date
    FROM all_source_dates
    WHERE source_date IS NOT NULL
)
SELECT
    TO_CHAR(calendar_date, 'YYYYMMDD')::INTEGER,
    calendar_date,
    EXTRACT(DAY FROM calendar_date)::SMALLINT,
    EXTRACT(ISODOW FROM calendar_date)::SMALLINT,
    TRIM(TO_CHAR(calendar_date, 'Day')),
    EXTRACT(WEEK FROM calendar_date)::SMALLINT,
    EXTRACT(MONTH FROM calendar_date)::SMALLINT,
    TRIM(TO_CHAR(calendar_date, 'Month')),
    EXTRACT(QUARTER FROM calendar_date)::SMALLINT,
    EXTRACT(YEAR FROM calendar_date)::SMALLINT,
    EXTRACT(ISODOW FROM calendar_date) IN (6, 7)
FROM GENERATE_SERIES(
    (SELECT min_date FROM date_boundaries),
    (SELECT max_date FROM date_boundaries),
    INTERVAL '1 day'
) AS dates(calendar_date);

