WITH item_totals AS (
    SELECT
        order_id,
        COUNT(*)::INTEGER AS item_count,
        SUM(price)::NUMERIC(14, 2) AS merchandise_value,
        SUM(freight_value)::NUMERIC(14, 2) AS freight_value
    FROM staging.stg_order_items
    GROUP BY order_id
),
payment_totals AS (
    SELECT
        order_id,
        SUM(payment_value)::NUMERIC(14, 2) AS payment_value
    FROM staging.stg_payments
    GROUP BY order_id
)
INSERT INTO warehouse.fact_order_lifecycle (
    order_id, customer_key, purchase_date_key, approved_date_key,
    delivered_date_key, estimated_delivery_date_key, order_status,
    order_purchase_timestamp, order_approved_at, order_delivered_customer_date,
    order_estimated_delivery_date, item_count, merchandise_value, freight_value,
    payment_value, approval_duration_minutes, delivery_duration_hours,
    delivery_delay_days, is_delivered_late, is_cancelled
)
SELECT
    o.order_id,
    COALESCE(c.customer_key, -1),
    TO_CHAR(o.order_purchase_timestamp, 'YYYYMMDD')::INTEGER,
    TO_CHAR(o.order_approved_at, 'YYYYMMDD')::INTEGER,
    TO_CHAR(o.order_delivered_customer_date, 'YYYYMMDD')::INTEGER,
    TO_CHAR(o.order_estimated_delivery_date, 'YYYYMMDD')::INTEGER,
    o.order_status,
    o.order_purchase_timestamp,
    o.order_approved_at,
    o.order_delivered_customer_date,
    o.order_estimated_delivery_date,
    COALESCE(i.item_count, 0),
    COALESCE(i.merchandise_value, 0),
    COALESCE(i.freight_value, 0),
    COALESCE(p.payment_value, 0),
    EXTRACT(EPOCH FROM (o.order_approved_at - o.order_purchase_timestamp)) / 60,
    EXTRACT(EPOCH FROM (o.order_delivered_customer_date - o.order_purchase_timestamp)) / 3600,
    EXTRACT(EPOCH FROM (
        o.order_delivered_customer_date - o.order_estimated_delivery_date
    )) / 86400,
    CASE
        WHEN o.order_delivered_customer_date IS NULL THEN NULL
        ELSE o.order_delivered_customer_date > o.order_estimated_delivery_date
    END,
    o.order_status = 'canceled'
FROM staging.stg_orders o
LEFT JOIN warehouse.dim_customer c ON o.customer_id = c.customer_id
LEFT JOIN item_totals i ON o.order_id = i.order_id
LEFT JOIN payment_totals p ON o.order_id = p.order_id;
