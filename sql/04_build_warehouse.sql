CREATE TABLE IF NOT EXISTS warehouse.dim_date (
    date_key       INTEGER PRIMARY KEY,
    full_date      DATE NOT NULL UNIQUE,
    day_of_month   SMALLINT NOT NULL,
    day_of_week    SMALLINT NOT NULL,
    day_name       VARCHAR(10) NOT NULL,
    week_of_year   SMALLINT NOT NULL,
    month_number   SMALLINT NOT NULL,
    month_name     VARCHAR(10) NOT NULL,
    quarter_number SMALLINT NOT NULL,
    year_number    SMALLINT NOT NULL,
    is_weekend     BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS warehouse.dim_customer (
    customer_key             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id              TEXT NOT NULL UNIQUE,
    customer_unique_id       TEXT,
    zip_code_prefix          INTEGER,
    city                     TEXT,
    state                    TEXT,
    latitude                 DOUBLE PRECISION,
    longitude                DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS warehouse.dim_product (
    product_key                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                  TEXT NOT NULL UNIQUE,
    category_name               TEXT,
    category_name_english       TEXT,
    product_name_length         INTEGER,
    product_description_length  INTEGER,
    product_photos_quantity     INTEGER,
    product_weight_g            NUMERIC(12, 2),
    product_length_cm           NUMERIC(12, 2),
    product_height_cm           NUMERIC(12, 2),
    product_width_cm            NUMERIC(12, 2)
);

CREATE TABLE IF NOT EXISTS warehouse.dim_seller (
    seller_key       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        TEXT NOT NULL UNIQUE,
    zip_code_prefix  INTEGER,
    city             TEXT,
    state            TEXT,
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS warehouse.fact_order_items (
    order_item_key      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id            TEXT NOT NULL,
    order_item_id       INTEGER NOT NULL,
    customer_key        BIGINT NOT NULL REFERENCES warehouse.dim_customer(customer_key),
    product_key         BIGINT NOT NULL REFERENCES warehouse.dim_product(product_key),
    seller_key          BIGINT NOT NULL REFERENCES warehouse.dim_seller(seller_key),
    order_date_key      INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
    shipping_date_key   INTEGER REFERENCES warehouse.dim_date(date_key),
    quantity            INTEGER NOT NULL DEFAULT 1,
    item_price          NUMERIC(12, 2) NOT NULL,
    freight_value       NUMERIC(12, 2) NOT NULL,
    total_item_value    NUMERIC(12, 2) NOT NULL,
    UNIQUE (order_id, order_item_id)
);

CREATE TABLE IF NOT EXISTS warehouse.fact_payments (
    payment_key          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id             TEXT NOT NULL,
    payment_sequential   INTEGER NOT NULL,
    customer_key         BIGINT NOT NULL REFERENCES warehouse.dim_customer(customer_key),
    payment_date_key     INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
    payment_type         TEXT NOT NULL,
    installment_count    INTEGER,
    payment_value        NUMERIC(12, 2) NOT NULL,
    UNIQUE (order_id, payment_sequential)
);

CREATE TABLE IF NOT EXISTS warehouse.fact_order_lifecycle (
    order_key                       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id                        TEXT NOT NULL UNIQUE,
    customer_key                    BIGINT NOT NULL REFERENCES warehouse.dim_customer(customer_key),
    purchase_date_key               INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
    approved_date_key               INTEGER REFERENCES warehouse.dim_date(date_key),
    delivered_date_key              INTEGER REFERENCES warehouse.dim_date(date_key),
    estimated_delivery_date_key     INTEGER REFERENCES warehouse.dim_date(date_key),
    order_status                    TEXT NOT NULL,
    order_purchase_timestamp        TIMESTAMP NOT NULL,
    order_approved_at               TIMESTAMP,
    order_delivered_customer_date   TIMESTAMP,
    order_estimated_delivery_date   TIMESTAMP,
    item_count                      INTEGER NOT NULL,
    merchandise_value               NUMERIC(14, 2) NOT NULL,
    freight_value                   NUMERIC(14, 2) NOT NULL,
    payment_value                   NUMERIC(14, 2) NOT NULL,
    approval_duration_minutes       NUMERIC(14, 2),
    delivery_duration_hours         NUMERIC(14, 2),
    delivery_delay_days             NUMERIC(14, 2),
    is_delivered_late               BOOLEAN,
    is_cancelled                    BOOLEAN NOT NULL
);

