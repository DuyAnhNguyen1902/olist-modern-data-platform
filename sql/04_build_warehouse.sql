INSERT INTO warehouse.fact_order_items (
    order_id, order_item_id, customer_key, product_key, seller_key,
    order_date_key, shipping_date_key, quantity, item_price, freight_value,
    total_item_value
)
SELECT
    i.order_id,
    i.order_item_id,
    COALESCE(c.customer_key, -1),
    COALESCE(p.product_key, -1),
    COALESCE(s.seller_key, -1),
    TO_CHAR(o.order_purchase_timestamp, 'YYYYMMDD')::INTEGER,
    TO_CHAR(i.shipping_limit_date, 'YYYYMMDD')::INTEGER,
    1,
    i.price,
    i.freight_value,
    i.price + i.freight_value
FROM staging.stg_order_items i
JOIN staging.stg_orders o ON i.order_id = o.order_id
LEFT JOIN warehouse.dim_customer c ON o.customer_id = c.customer_id
LEFT JOIN warehouse.dim_product p ON i.product_id = p.product_id
LEFT JOIN warehouse.dim_seller s ON i.seller_id = s.seller_id;

